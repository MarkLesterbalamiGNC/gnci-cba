<?php
/**
 * employee_report_download.php
 * Lets an employee download THEIR OWN attendance report as a file (PDF or Word)
 * instead of using the browser's print preview. Uses the same dates / status filter as My Report.
 *   employee_report_download.php?format=pdf|word&from=YYYY-MM-DD&to=YYYY-MM-DD&status=Present|Late|Absent
 */
require_once 'includes/auth.php';
require_once 'config/db.php';
require_once 'includes/auth_role.php';
require_employee();

require_once 'includes/attendance_summary.php';
require_once 'includes/schedule_functions.php';
require_once 'includes/report_export.php';

$empId = (int)($_SESSION['employee_id'] ?? 0);
$stmt = $pdo->prepare("SELECT * FROM employees WHERE id = ? AND deleted_at IS NULL");
$stmt->execute([$empId]);
$emp = $stmt->fetch();
if (!$emp) {
    header('Location: login.php');
    exit;
}

// Dates: same defaults as My Report, but ignore anything that is not a real date
$validDate = function ($s): bool {
    return is_string($s) && preg_match('/^\d{4}-\d{2}-\d{2}$/', $s)
        && checkdate((int)substr($s, 5, 2), (int)substr($s, 8, 2), (int)substr($s, 0, 4));
};
$from = $validDate($_GET['from'] ?? null) ? $_GET['from'] : date('Y-m-01');
$to   = $validDate($_GET['to'] ?? null)   ? $_GET['to']   : date('Y-m-d');
if ($from > $to) { [$from, $to] = [$to, $from]; }

$statusFilter = att_status_from_get();
$format = $_GET['format'] ?? 'pdf';
if (!in_array($format, ['pdf', 'word'], true)) $format = 'pdf';

// Schedule (shifts) assigned to this employee
$schedule = !empty($emp['schedule_id']) ? get_schedule((int)$emp['schedule_id']) : null;
$shifts   = $schedule ? get_schedule_shifts((int)$schedule['id']) : [];

// Same numbers as the My Report page
$stmt = $pdo->prepare("SELECT * FROM attendance WHERE employee_id = ? AND log_date BETWEEN ? AND ?");
$stmt->execute([$empId, $from, $to]);
$logRows = $stmt->fetchAll();

$attended   = att_attended_days($logRows);
$absentDays = att_absent_days(att_date_list($from, $to), $attended, $emp['created_at'], att_excused_dates($pdo, $empId));
[$stats, $allRows] = att_build($logRows, $absentDays);
$rows = att_filter($allRows, $statusFilter);

$fmtHours = function (int $min): string {
    return intdiv($min, 60) . 'h ' . str_pad((string)($min % 60), 2, '0', STR_PAD_LEFT) . 'm';
};
$totalMinutes = 0;
$tableRows = [];
foreach ($rows as $i => $r) {
    $minutes = null;
    if (empty($r['absent']) && $r['time_in'] && $r['time_out']) {
        $m = (int)round((strtotime($r['time_out']) - strtotime($r['time_in'])) / 60);
        if ($m > 0) { $minutes = $m; $totalMinutes += $m; }
    }
    $absent = !empty($r['absent']);
    $tableRows[] = [
        (string)($i + 1),
        (string)$r['log_date'],
        $absent ? '-' : (string)($r['shift_label'] ?: 'Shift ' . $r['shift_order']),
        $r['time_in']  ? format_time_am_pm($r['time_in'])  : '-',
        $r['time_out'] ? format_time_am_pm($r['time_out']) : '-',
        $minutes ? $fmtHours($minutes) : '-',
        (string)$r['status'],
    ];
}
$attendedDays   = $stats['present'] + $stats['late'];
$attendanceRate = $stats['total'] > 0 ? round($attendedDays / $stats['total'] * 100) : 0;

$schedLines = [];
if ($schedule) {
    $schedLines[] = (string)$schedule['name'];
    foreach ($shifts as $sh) {
        $schedLines[] = $sh['label'] . ': ' . format_time_am_pm($sh['time_start']) . ' - ' . format_time_am_pm($sh['time_end'])
                      . ' (' . (int)$sh['grace_minutes'] . ' min grace)';
    }
} else {
    $schedLines[] = 'No schedule assigned';
}

$doc = [
    'title'    => $emp['name'] . ' - Attendance Report',
    'subtitle' => $from . ' to ' . $to . ($statusFilter ? ' - ' . $statusFilter . ' only' : ''),
    'details'  => [
        ['Full Name',   (string)$emp['name']],
        ['Employee ID', (string)$emp['employee_id']],
        ['Department',  (string)$emp['department']],
        ['Course',      $emp['course'] ? (string)$emp['course'] : '-'],
        ['Position',    (string)$emp['position']],
        ['Email',       (string)$emp['email']],
        ['Mobile No.',  (string)$emp['mobile_no']],
    ],
    'schedule' => $schedLines,
    'summary'  => 'Attendance rate: ' . (int)$attendanceRate . '%   |   Total hours: ' . $fmtHours($totalMinutes),
    'head'     => ['#', 'Date', 'Shift', 'Time In', 'Time Out', 'Hours', 'Status'],
    'rows'     => $tableRows,
    'footer'   => 'Generated by BioTrack - GNCI CBA on ' . date('M j, Y g:i A'),
];

// Build the file
$data = null; $mime = ''; $ext = '';
if ($format === 'word') {
    $data = rx_docx($doc);
    if ($data !== null) { $mime = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'; $ext = 'docx'; }
    else { $data = rx_doc_html($doc); $mime = 'application/msword'; $ext = 'doc'; }
} else {
    $data = rx_pdf($doc);
    $mime = 'application/pdf'; $ext = 'pdf';
}

$safeId = preg_replace('/[^A-Za-z0-9_-]/', '', (string)$emp['employee_id']);
$filename = 'Attendance_Report_' . $safeId . '_' . $from . '_to_' . $to . '.' . $ext;

while (ob_get_level() > 0) ob_end_clean();
header('Content-Type: ' . $mime);
header('Content-Disposition: attachment; filename="' . $filename . '"');
header('Content-Length: ' . strlen($data));
header('Cache-Control: private, no-store');
header('X-Content-Type-Options: nosniff');
echo $data;
exit;
